export function sdFormatDuration(minutes: number): string {
  if (minutes < 60) return `~${minutes} mins`;
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return m === 0 ? `~${h} hr${h > 1 ? "s" : ""}` : `~${h}.${Math.round(m / 6)} hours`;
}
