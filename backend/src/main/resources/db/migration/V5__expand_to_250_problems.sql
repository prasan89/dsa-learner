  INSERT INTO problems (id, slug, title, difficulty, description, constraints, examples, active)
  SELECT gen_random_uuid(), slug, title, difficulty,
         'Master ' || title || ' in Java. Identify the underlying ' || pattern_slug ||
         ' pattern, reason about edge cases, and implement an efficient solution.',
         CASE difficulty WHEN 'EASY' THEN '1 <= n <= 10^4'
                         WHEN 'MEDIUM' THEN '1 <= n <= 10^5'
                         ELSE '1 <= n <= 2 * 10^5' END,
         '[{"input":"See lesson examples","output":"See lesson examples"}]'::jsonb,
         true
  FROM new_data
  ON CONFLICT (slug) DO NOTHING
  RETURNING id, slug
)
INSERT INTO problem_patterns (problem_id, pattern_id)
SELECT i.id, p.id
FROM inserted i
JOIN new_data d ON d.slug = i.slug
JOIN patterns p ON p.slug = d.pattern_slug
ON CONFLICT DO NOTHING;